"""Площадь и периметр прямоугольника."""


def area(a, b):
    """Считает площадь прямоугольника по двум соседним сторонам.

    Формула: S = a * b.

    Аргументы:
        a (число): Длина одной стороны.
        b (число): Длина соседней стороны.

    Возвращает:
        число: Площадь прямоугольника.

    Пример вызова:
        >>> area(3, 5)
        15
    """
    return a * b


def perimeter(a, b):
    """Считает периметр прямоугольника по двум соседним сторонам.

    Формула: P = 2 * (a + b).

    Аргументы:
        a (число): Длина одной стороны.
        b (число): Длина соседней стороны.

    Возвращает:
        число: Периметр прямоугольника.

    Пример вызова:
        >>> perimeter(3, 5)
        16
    """
    return 2 * (a + b)
