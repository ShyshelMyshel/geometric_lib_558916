"""Площадь и периметр треугольника."""

def area(a, h):
    """Считает площадь треугольника по основанию и опущенной на него высоте.

    Формула: S = a * h / 2.

    Аргументы:
        a (число): Длина основания.
        h (число): Высота, опущенная на основание a.

    Возвращает:
        число: Площадь треугольника.

    Пример вызова:
        >>> area(10, 3)
        15.0
    """
    return a * h / 2


